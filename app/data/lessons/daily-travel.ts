type WordSeed = [korean: string, chinese: string, english: string, emoji: string];

function lesson(id: string, titleChinese: string, titleKorean: string, seeds: WordSeed[]): Lesson {
  return {
    id,
    titleChinese,
    titleKorean,
    words: seeds.map(([korean, chinese, english, emoji], index): LessonWord => ({
      id: `travel-${id}-${index + 1}`,
      korean, chinese, english, emoji,
    })),
  };
}

